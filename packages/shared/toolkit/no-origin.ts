/**
 * 「这次调用不是从任何一条会话里发起的」——调度、deeplink、CLI、界面上一个与当前
 * 会话无关的按钮(K2a)。
 *
 * 它是一个**保留坐标**,不是某条会话的 id:`Invocation.sessionId` 在 toolkit 里是
 * 必填的(它是审计与取消的坐标,不是可选的元数据),而「没有发起会话」是一个真实
 * 存在的答案。给它一个具名的值,好过让每个无会话调用方随手编一条 id —— 那样审计
 * 会落进一条不存在的会话,或者更糟,落进**被改的那一条**(K1 留账说的正是这个:
 * 重命名会话 A 时若拿 A 当发起坐标,审计就变成了「A 自己改了自己」)。
 *
 * `@` 开头是刻意的:id 是 uuid,字母表里没有 `@`,所以它与任何真 id 都撞不上,而且
 * 一眼看得出不是 id。谁读到这个坐标,谁负责把审计落到别处 —— 今天唯一的读者是
 * `backend/toolkit/toolkit-audit-sink.ts`(落 `<store>/audit/resource.jsonl`)。
 *
 * 字面量里**不写出那个命名空间的名字**:资源内核不认识任何 scheme(§2 不变量 3),
 * 而资源目录的 `__tests__/stranger.test.ts` 按词边界扫那个目录来执法 —— 这一条是它当场抓出来的,
 * 而且抓对了:一个叫 `@no-origin-<某个 scheme 名>` 的保留坐标,读起来像是那种资源
 * 的特例,而它不是。
 *
 * 为什么住在 shared(D191,2026-10-04 从 `backend/resource/resource-kernel.ts` 搬来):它是契约里的一个保留值,
 * 不是资源内核的逻辑。资源内核在「不给发起会话」时填它,工具的审计落盘口读到它就换一本账落 —— 两边要认同一个值,
 * 而审计落盘口不该为了一个常量去认识资源内核(那条边让工具目录的入口闭包长出资源功能)。资源入口照旧原样再交出它。
 * 文件名叫 `no-origin` 而不带「session」这个词,也是上面那道词边界门的缘故:资源内核引它的那一行在被扫的文件里。
 */
export const NO_ORIGIN_SESSION = '@no-origin'
