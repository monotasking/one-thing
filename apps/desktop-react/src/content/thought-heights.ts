import { HeightBook } from '../ui/flip-height'

/**
 * 思考段的高账本 —— **这一族共用一只 `ResizeObserver`** 记住「此刻多高」,
 * 给收尾那一下折叠的 FLIP 当「改前」的起点(单 B ④,正本 §2 规矩 ④)。
 *
 * ── 为什么它要自己一本(与 `tools/card-heights.ts` 同一条判词)────────────
 * 账本的 `size` 是一个读得出的数,谁在里面就该说得清。工具卡那一族是 916 只
 * 一起进场的盒子,思考段这一族是一条会话里几十到几百段各自长着的字 —— 挤进
 * 同一只观察者,下一个人读那个数时说不清它在说谁。两只 RO 的成本是常数。
 *
 * ── 为什么「改前」不能现问 ────────────────────────────────────────────────
 * 收尾那一帧要的起点是**折之前那一段有多高**,而那一段在 20 万字的会话上是
 * 6 万像素;现问一次 `offsetHeight` 就是把整棵挂着 `content-visibility: auto`
 * 的消息树当场逼出来排一次版(病历整段在 `ui/flip-height.ts` 的文件头:
 * 916 张卡各读一次 = prod 770ms，占那一帧的 74%)。RO 的回调跑在排版**之后**,
 * 它报过来的那个数是浏览器刚算完的,读它不逼任何人重排 —— 而思考段在流式期间
 * 本来就每帧在长,那个数一路都是新的。
 */

/** 全壳思考段的那一本。模块级单例 —— 按 09-01 立法配 HMR 退役(复用它自己那口 `reset()`)。 */
export const thoughtHeights = new HeightBook()

if (import.meta.hot) {
  import.meta.hot.dispose(() => thoughtHeights.reset())
}
