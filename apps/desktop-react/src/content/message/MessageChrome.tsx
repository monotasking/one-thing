import type { ReactNode } from 'react'
import s from './MessageChrome.module.css'

/**
 * **消息外缘那一行 —— 三张脸同格同高**(2026-09-15 单 B ⑤;正本
 * `docs/send-flow-2026-09.md` §2 规矩 ⑤)。
 *
 * ── 它治的是哪一件事 ──────────────────────────────────────────────────────
 * 「同一个位置,永远只有一个在」这句话从 08-31 起就写在 `MessageChrome.module.css`
 * 的文件头上,可**实现上它一直是条件渲染**:流式中挂读数行,收尾那一帧卸掉读数行、
 * 挂上动作行 —— 两者高度不同,于是收尾那一帧**内容缩了一截**。
 *
 * 单 A 的门把这一截量出来了:发送之后气泡在置顶线上一动不动(换手位移 0.0px),
 * **可收尾那一帧它会漂 12px**,一帧之后座位补回来又回到原位。那 12px 不是别的,
 * 正是这一行换脸时的高度差(外加流式光标那一格)。一帧 8ms 的瞬态,但它是
 * 「视口不动」这条规矩上的一个洞 —— 洞要堵在**源头**:这一行的高度从头到尾不变。
 *
 * ── 怎么做到「不变」────────────────────────────────────────────────────────
 * 一格 grid,几张脸**全部落在同一格**(`grid-area: 1 / 1`),所以这一行的高
 * 恒等于**最高那一张脸**,与此刻显示哪一张无关。换脸只换 `opacity`
 * (`--dur-flash`,240ms 交叉淡入)。
 *
 * **动作行常驻在 DOM 里**这件事不是这一批发明的 —— 它从 08-31 起就是常驻的
 * (幽灵动作行的第一条纪律:条件渲染会让它浮现时把下文推下去)。这一批做的是
 * **把读数行也搬进同一格**,于是那条老纪律从「动作行自己不推下文」升级成
 * 「整条外缘不推下文」。
 *
 * ── 读数行为什么不常驻 ────────────────────────────────────────────────────
 * 它身上挂着一只 100ms 的 `setInterval`(`READOUT_TICK_MS`)。一条 400 条消息的
 * 会话里常驻就是 400 只表,而它一秒钟要醒十次 —— 那是拿「高度稳定」去换一笔
 * 按会话长度计价的账,与第 5 轴那条法正面相撞。
 *
 * 不常驻也照样高度稳定,因为**动作行才是高的那一张**(它的字号是 `--fs-meta`、
 * 钮有 `--sp-1` 的上下内距;读数行是 `--fs-micro`、钮零上下内距)。动作行常驻 =
 * 这一格的高常驻。真机读数在门的 ②b 那一行上。
 *
 * ── 收场通知是第四件,不在这一格里 ────────────────────────────────────────
 * 「为什么这一轮提前结束」是**动作行上面的一句陈述**,不是第三态(判词在
 * `ChatStream.tsx` 摆它的那一处)。它与动作行**同时在场**,所以它自己一行 ——
 * 而且它是**事后出现的**(收尾那一帧才知道),所以走 `.rowLate` 软着陆,
 * 与上下文更新折痕同一条判例、同一套过渡。
 *
 * ── 三张状态表 ────────────────────────────────────────────────────────────
 * ① 生命周期:纯布局件,零 state / 零订阅 / 零计时器 / 零模块级副作用 →
 *    **不需要 HMR dispose**。它只有一种宿主:一条助手消息的末尾。
 * ② UI 生命状态:两态 —— 流式中(读数在前)/ 收尾后(动作在前)。没有 empty
 *    (没有脸的时候这一件根本不渲染)、没有 loading / error。**超量**不成立:
 *    它不吃数据,脸的数量是常数。
 * ③ UI 交互状态:这一件自己只有「哪张脸亮着」;rest / hover / focus 归各张脸
 *    (动作行的幽灵浮现判据仍是 `[data-message-id]:hover`,一个字没动)。
 */
export function MessageChrome({
  /** 流式中那一张脸(读数 · 耗时 · 停止)。收尾后不渲染 —— 它带着一只计时器。 */
  readout,
  /** 收尾后那一张脸(复制 / 重试)。**常驻**:这一格的高由它说了算。 */
  actions,
  /** 此刻哪一张在前。`true` = 读数。 */
  streaming,
}: {
  readout?: ReactNode
  actions?: ReactNode
  streaming: boolean
}) {
  if (!readout && !actions) return null
  return (
    <div className={s.chrome} data-testid="chat-chrome" data-face={streaming ? 'readout' : 'actions'}>
      {/*
        * 两张脸都挂 `data-on`:亮的那一张 opacity 1,暗的那一张 0 且 `inert`
        * (不许被 Tab 走到、不许被读屏念到 —— 一张看不见的脸还能接焦点比没有焦点更糟)。
        * `inert` 而不是 `hidden` / `display:none`:后两者会把它从布局里摘掉,
        * 这一格的高就又跟着此刻显示哪张脸变了 —— 那正是要治的病。
        */}
      {readout && (
        <div className={s.face} data-on={streaming || undefined} inert={!streaming}>
          {readout}
        </div>
      )}
      {actions && (
        <div className={s.face} data-on={!streaming || undefined} inert={streaming}>
          {actions}
        </div>
      )}
    </div>
  )
}
