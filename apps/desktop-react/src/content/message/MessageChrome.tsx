import type { ReactNode } from 'react'
import s from './MessageChrome.module.css'

/**
 * **消息外缘那一行 —— 一格常驻的动作格**(2026-09-15 单 B ⑤ 立件;
 * 2026-09-20 G 线 P1 把读数那张脸搬走了)。
 *
 * ── 它今天治的是哪一件事 ──────────────────────────────────────────────────
 * 「同一个位置,永远只有一个在」这句话从 08-31 起就写在
 * `MessageChrome.module.css` 的文件头上,可实现上它一直是条件渲染:流式中挂读数行,
 * 收尾那一帧卸掉读数行、挂上动作行 —— 两者高度不同,于是收尾那一帧**内容缩了一截**
 * (单 A 的门量到 12px)。单 B ⑤ 的治法是一格 grid、两张脸同格同高。
 *
 * **G 线 P1 把那两张脸拆成了一张半**:读数行(与那枚呼吸光标)整个搬去了整列末尾
 * 的尾槽(`content/message/TailSlot.tsx`),判词在正本
 * `docs/stream-geometry-2026-09.md` §0 的 ④ 与 §1 的 G4 —— **只在流式期存在的东西
 * 不许住在流里**:它排在正文之后,正文长一段它就被推一段(真机量到整轮动 303 次、
 * 单帧最大 335px、方向反转 3 次)。
 *
 * 于是这一件只剩**一张脸**:幽灵动作行。它**仍然常驻**、仍然只动 `opacity` ——
 * 那是 08-31 起就有的第一条纪律(条件渲染会让它浮现时把下文推下去),与读数行搬不
 * 搬家无关。一格 grid 也留着:一张脸落在 `1 / 1` 与不落在没有区别,而它是「这一行
 * 将来还可能有第二张脸」这件事在结构上的留白 —— 真有第二张时拼上去就够,这个文件
 * 一行不改。
 *
 * ── 收场通知是另一件,不在这一格里 ────────────────────────────────────────
 * 「为什么这一轮提前结束」是**动作行上面的一句陈述**,不是第二张脸(判词在
 * `ChatStream.tsx` 摆它的那一处)。它与动作行**同时在场**,所以它自己一行 ——
 * 而且它是**事后出现的**(收尾那一帧才知道),所以走 `.lateRow` 软着陆。
 *
 * ── 三张状态表 ────────────────────────────────────────────────────────────
 * ① 生命周期:纯布局件,零 state / 零订阅 / 零计时器 / 零模块级副作用 →
 *    **不需要 HMR dispose**。它只有一种宿主:一条助手消息的末尾。
 * ② UI 生命状态:两态 —— 流式中(动作格暗着 + `inert`)/ 收尾后(动作格亮着)。
 *    没有 empty(没有动作的时候这一件根本不渲染)、没有 loading / error。
 *    **超量**不成立:它不吃数据,脸的数量是常数。
 * ③ UI 交互状态:这一件自己只有「亮不亮」;rest / hover / focus 归动作行
 *    (幽灵浮现判据仍是 `[data-message-id]:hover`,一个字没动)。
 */
export function MessageChrome({
  /** 收尾后那一张脸(复制 / 重试)。**常驻**:这一格的高由它说了算。 */
  actions,
  /**
   * 这一轮还在跑吗。`true` = 动作格暗着 + `inert`(这一刻不该被 Tab 走到、
   * 也不该被读屏念到:一条还在写的回复,「重试」与「复制」都还不是它的动作)。
   */
  streaming,
}: {
  actions?: ReactNode
  streaming: boolean
}) {
  if (!actions) return null
  return (
    <div
      className={s.chrome}
      data-testid="chat-chrome"
      /*
       * 此刻哪一张脸在前。**`none` 是 G 线 P1 之后的新词** —— 从前它是 `readout`
       * (读数那张在前),而那张脸已经搬去尾槽了,再写 `readout` 就是说谎。
       */
      data-face={streaming ? 'none' : 'actions'}
    >
      {/*
        * 动作格挂 `data-on`:亮的那一张 opacity 1,暗的那一张 0 且 `inert`
        * (不许被 Tab 走到、不许被读屏念到 —— 一张看不见的脸还能接焦点比没有焦点更糟)。
        * `inert` 而不是 `hidden` / `display:none`:后两者会把它从布局里摘掉,
        * 这一格的高就又跟着此刻显示哪张脸变了 —— 那正是要治的病。
        */}
      <div className={s.face} data-on={!streaming || undefined} inert={streaming}>
        {actions}
      </div>
    </div>
  )
}
