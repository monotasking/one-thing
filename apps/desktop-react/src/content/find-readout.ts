/**
 * **「找到第几处 / 共几处」那一格字面 —— 全壳唯一一个产地**(B3-b,结清 T2 与
 * B3-a 各自留下的那条账:两份逐字同形的读数函数)。
 *
 * ── 病 ────────────────────────────────────────────────────────────────────
 * 终端查找行(T2)与网页查找行(B3-a)各写了一只:`TerminalLeaf.findReadout`
 * 收 `{query, index, count}`,`browser-find.browserFindReadout` 收
 * `{query, active, total}`。三档判据(没词 → 不画 / 零命中 → `0` / 序号未知 →
 * 只报总数)一模一样,两处各有一份注释、各有一组单测。同一句话两个产地,
 * 改一处忘一处就是两条查找行读数不同 —— 而人根本分不出那是两套代码。
 *
 * ── 合的是判据,不是口径 ──────────────────────────────────────────────────
 * 两边喂进来的序号**基不同**,而那不是可以随手抹平的分歧:
 *  · 终端那一格来自 `@xterm/addon-search` 的 `resultIndex`,**0 起**,`-1` =
 *    「插件还没说停在第几处」(超出高亮上限时就是这一形);
 *  · 网页那一格来自 Chromium 的 `activeMatchOrdinal`,**1 起**,`0` = 「这一发
 *    中间结果只报了总数」(判词在 `electron/browser/find.ts` 上)。
 *
 * 所以这只函数收的是**归一之后**的 `ordinal`:**1 起,`<= 0` = 不知道**。
 * 两边各自在调用点把自己的原口径折进来(终端 `index + 1`,网页原样),于是
 * 「Chromium 报的就是这个数」与「壳算错了」仍旧分得开 —— 那正是 B3-a 当初
 * 不肯在推送通道里折口径的理由,这次只是把折的位置定在了**调用点**,
 * 而不是让两只函数各带一套。
 *
 * 纯函数、零 import:所以两边的渲染树谁都不必为了这一格把对方拖进来
 * (`data/browser-find.ts` 的文件头当初正是为了躲开 `TerminalLeaf` 那条边
 * 才自己抄了一份 —— 那条边今天不存在了)。
 */

export interface FindReadout {
  /** 人此刻在找的那个词。空 = 还没开始找。 */
  query: string
  /** 当前命中的序号,**1 起**;`<= 0` = 不知道停在第几处(只报总数)。 */
  ordinal: number
  /** 总命中数。 */
  total: number
}

/**
 * 三档 + 「不画」。
 *
 * | 输入 | 答 | 屏幕上 |
 * | --- | --- | --- |
 * | 没词 | `null` | 这一格整个不画(「没内容就别占地方」) |
 * | 有词、零命中 | `'0'` | 一个 0。**不变红、不抖、不弹东西** |
 * | 有词、有命中、序号不知道 | `'17'` | 只报总数 —— **不编一个序号出来** |
 * | 有词、有命中、序号知道 | `'3/17'` | 第几处 / 共几处 |
 */
export function findReadout(find: FindReadout): string | null {
  if (!find.query) return null
  if (find.total <= 0) return '0'
  return find.ordinal <= 0 ? String(find.total) : `${find.ordinal}/${find.total}`
}
