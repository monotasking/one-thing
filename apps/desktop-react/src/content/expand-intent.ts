import { createContext, useContext } from 'react'

/**
 * **「用户在流里点开了一样东西」这一件意图的唯一通道**(2026-09-12 报障二的「位」)。
 *
 * ── 为什么非要一条通道不可 ────────────────────────────────────────────────
 * 聊天流的跟随判据是**几何**(`content/follow.ts` 文件头:没有计时器、没有「这一下
 * 是我自己滚的」标志位,判据只有位置)。那条纪律成立,是因为它管的全是**滚动**:
 * 滚动的每一种来源最后都落在同一个位置读数上。可是「内容长高」不一样 ——
 *   · 模型又吐了一段 → 内容长高,gap 变大,scrollTop 不动;
 *   · 用户点开了一段思考 / 一张工具卡 / 一道折痕 → 内容长高,gap 变大,scrollTop 不动。
 * **这两件事在几何上逐字相同**,量多少遍都分不出来。而它俩要的结果正好相反:前者
 * 该跟底(那是他在等的回复),后者绝不能跟底(他要读的正是刚点开的那一段,跟一下
 * 屏幕当场滑到最底,展开的内容反而看不见了 —— 这就是报障二)。
 *
 * 几何分不出来的事,只能由**知道自己在做什么的那一方自述**。所以它是一条 context:
 * 点开的那个组件报一句「是我」,聊天流据此在接下来一小段时间里按兵不动
 * (`components/motion.ts` 的 `EXPAND_HOLD_MS`,判词在那儿)。
 *
 * ── 它不是一个标志位 ──────────────────────────────────────────────────────
 * 与 follow.ts 文件头禁掉的那种标志位的区别是**它记的是什么**:那种标志位记的是
 * 「这一次滚动是不是我发起的」—— 要为 wheel / 键盘 / 拖滚动条 / scrollIntoView /
 * 浏览器滚动锚定每一条来源各记一次,漏一条就是一次跟不住。这里记的是一件**与几何
 * 无关的意图**(人动了手)以及它伴随的那段动画有多长,产地只有「按下展开」这一处。
 *
 * ── 缺省是 noop ───────────────────────────────────────────────────────────
 * 流之外照样有消费者(Gallery 样例页、单测里直接渲染折痕)。缺省 noop 让它们一个字
 * 都不必知道有这回事 —— 报给没人听的地方,等于没报。
 */
export const ExpandIntentContext = createContext<() => void>(() => {})

/**
 * 「我这一下是用户点开的,别贴底」。
 *
 * 消费点**只在「打开」那一下叫**,收起不叫:收起是内容变矮,跟底那一半本来就
 * 不会因为变矮而动(`stick` 只在 pinned 时把位置赋到底,而变矮时那个位置就是原位)。
 */
export function useNoteUserExpand(): () => void {
  return useContext(ExpandIntentContext)
}
