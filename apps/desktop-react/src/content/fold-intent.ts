import { createContext, useContext } from 'react'

/**
 * **「流里有一块正在折起来」这一件事的唯一通道**(2026-09-15,单 B ④;
 * 正本 `docs/send-flow-2026-09.md` §2 规矩 ④)。
 *
 * 它是 `content/expand-intent.ts` 的**另一半**,两条通道的形逐字相同(context +
 * 一句自述),方向相反:
 *   · 展开 —— 内容**长高**,几何上与「模型又吐了一段」逐字相同,所以要一句自述
 *     才分得出「别贴底」;
 *   · 折起 —— 内容**变矮**,几何上与「一条消息被删了」逐字相同,而它俩要的结果
 *     同样相反:删一条消息该让下面的内容自然上来,折一块正在读的东西**必须把
 *     视口钉在他正在读的那一行上**,不然屏幕当场往上抽一大截。
 *
 * ── 它治的是哪一件事故 ────────────────────────────────────────────────────
 * 正本 §0 三处病之二:一轮跑完那一帧思考段自动折回一行,**6 万像素缩成 783px**,
 * 上一条用户消息的 top 从 −60,879 跳到 −286(真机探针 `probe-stream-end.mjs`)——
 * 整屏跳变。病根不是折叠本身(折是对的:想完了它就该退回成一行索引),是
 * **折的时候没有人钉住视口**。
 *
 * ── 为什么记的是「到什么时候为止」,不是一个布尔闩 ────────────────────────
 * 与 `EXPAND_HOLD_MS` 同一条理由(那段判词在 `components/motion.ts`):折叠是一段
 * **过渡**,尺寸变化会**逐帧**来好几次,一次性闩被第一帧消费掉之后,后面那几帧
 * 照旧跟底 —— 事故仍在。所以报的是一个**时长**,聊天流把它换算成截止时刻。
 *
 * ── 缺省是 noop ───────────────────────────────────────────────────────────
 * 与展开那条同判:流之外照样有消费者(Gallery 样例页、单测里直接渲染思考段),
 * 报给没人听的地方等于没报。
 */
export const FoldIntentContext = createContext<(ms: number) => void>(() => {})

/**
 * 「我这一块开始往回折了,接下来 `ms` 毫秒里请钉住视口」。
 *
 * **在开始折的那一帧叫**(与那段高度过渡同一个 layout effect),不是折完之后 ——
 * 折完再说就什么都来不及了。`ms` 用那段过渡自己的时长(`CARD_FLIP_MS`),
 * 调用方不许现写一个数:时长的产地只有 `components/motion.ts`。
 */
export function useNoteFold(): (ms: number) => void {
  return useContext(FoldIntentContext)
}
