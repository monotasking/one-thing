import type { BlockModel } from '../model/blocks'
import type { SegmentModel } from '../model/segments'

/**
 * 管线第 ⑤ 步:**稳定 key**(§2 / §6)。
 *
 * ── 为什么这是一步、而不是渲染时随手 `index` ────────────────────────────
 * key 稳定性是**硬约束**,不是整洁癖。流式期间同一段文本每帧重解析一次,key 一变
 * React 就丢弃旧子树重建 —— 代码块逐帧重挂、滚动位置归零、shiki 逐帧重染。
 * tab 卡顿那一批的教训原样重演一遍(整棵卸载重建 = 长帧),所以它单独成一步、
 * 单独有单测。
 *
 * ── 为什么 key 不进模型 ──────────────────────────────────────────────
 * 模型是数据,key 是**渲染的事**:同一份段模型在别处(比如导出、复制)不需要 key,
 * 而且往模型里塞一个只有 React 读的字段,深比、序列化、快照测试都会被它污染。
 * 所以 key 是**纯函数派生**——给同一份输入永远算出同一个字符串。
 *
 * ── 段按序号,块按源偏移 ──────────────────────────────────────────────
 * 段序列**只在末尾增长**,序号因此天然稳定。P2 的锚点归位没有动摇这一条:工具段
 * 是按 `turnIndex` 就位的,而一轮的工具只会在**那一轮的正文之后**出现 —— 下一轮的
 * 正文存在就意味着上一轮已经收场,所以中段不会凭空插进一个段把后面全体推走。
 * (「末尾追加一张工具卡,前面的 key 一个都不变」那条用例钉的正是它。)
 *
 * **块不是**:P1 真解析器进来之后,一段正文中间长出一个新块会让它后面所有
 * 块的下标平移一格 —— 按下标发 key 的话,那一帧后面每一块都是「换了 key 的新东西」,
 * React 全部重挂:代码块重染、滚动位置归零、表格重排。
 *
 * 所以块 key 改由**源偏移**派生:一个块的身份 = 它从源文本的哪个字符开始。追加不改
 * 前面任何一块的起点,于是流式重解析出来的 key 逐字相等,React 只打补丁。
 * (这一条有单测钉着:同一段文本按帧喂进去,每一帧的 key 集合逐字相等。)
 */

/**
 * 段 key。带上 `kind`:同一个位置从一种段变成另一种段时,那本来就该是两个组件,
 * 让 React 重挂是对的(复用会把上一种段的状态带进新组件)。
 */
export function segmentKey(messageId: string, index: number, segment: SegmentModel): string {
  return `${messageId}:${index}:${segment.kind}`
}

/**
 * 块 key。挂在所属段的 key 下 —— 段换了,块自然全换,不必再判一次。
 *
 * `offset` 是源偏移(rich-text 段随块一起带出来的解析事实)。拿不到时退回下标:
 * 工具产地的块序列不来自一段源文本,没有偏移可言,而它也不会在流式期间中段插入。
 *
 * 带上 `kind`:同一个起点上的块**换了型**(未闭合围栏闭合那一刻由 code 换成 table),
 * 那本来就该是两个组件,让 React 重挂是对的 —— 复用会把上一种块的状态(展开态、
 * 横滚位置)带进新组件。这正是「原位换装」里的「换装」。
 */
export function blockKey(
  segmentKeyValue: string,
  index: number,
  block: BlockModel,
  offset?: number,
  id?: string,
): string {
  // R4a:块流给了号就用号 —— 身份从「渲染侧现算」变成「流上带着」,这一行是那次
  // 反转在渲染侧的全部落点。号本身就是产地派生的(`${偏移}:${kind}`),所以两条路
  // 拼出来的字符串逐字相同,开关一翻不会让整条消息重挂。
  if (id !== undefined) return `${segmentKeyValue}/${id}`
  return `${segmentKeyValue}/${offset ?? index}:${block.kind}`
}
