/**
 * **起拖阈值**(W3 裁定 3)。
 *
 * 「按下去几个像素之后才算在拖」是**指针手势的语法**,不是拼贴台的规矩 ——
 * 一颗按钮、一行列表、一格 tab 用的都是同一个数,所以它住在 ui 层。
 *
 * ── 三个阈值,三个名字,禁合并(裁定 3 的原话)────────────────────────────
 *   `DRAG_START_PX`(这里,8)          按下多少像素之后这一下才不再是「点击」
 *   `TEAR_OFF_DISTANCE`(24, `stage/transitions.ts`) 从架子上往主区拖多远算「撕下来」
 *   `SNAP_BAND`(24, `stage/transitions.ts`)         离窗口边多近算「要钉上去」
 *
 * 后两个是**形态机**的数(它们量的是「离某条边多远」,单位是那条边的语义),
 * 这一个是**手势**的数(它量的是「手抖了没有」)。三者今天有两个恰好相等,
 * 那是巧合不是同一件事:把它们并成一个常量,以后调「手别抖」的灵敏度会连带
 * 改掉「吸边有多灵」,而那两件事的用户反馈来自完全不同的场合。
 */
/**
 * **09-05 从 4 调到 8**(W3-b 裁定,用户原话:「4px 就起拖,轻轻一碰浮影就出来」)。
 *
 * 4 是「手抖了没有」的下界,不是「用户是不是想拖」的判据 —— 在触控板上把手指
 * 从按下到抬起,横向漂 4~6px 是常态,于是一次**想点**的点击有一半概率先冒出一枚
 * 浮影再消失。8 是 Chromium 自己那条 `kDragThresholdX/Y`(以及 macOS 与
 * GTK 的默认拖拽阈值)用的数,来源是真人手感而不是像素洁癖。
 *
 * 上面那张表的另一半照旧:这一个是**手势**的数,`TEAR_OFF_DISTANCE` / `SNAP_BAND`
 * 是**形态机**的数。它们今天都不再相等,三者从此在数值上也看得出是三件事。
 */
export const DRAG_START_PX = 8

/**
 * **一格标签横向起拖**(W6-b,设计 `docs/workbench-tabs-2026-09.md` §4.1)。
 *
 * 它与 `DRAG_START_PX` **并存,各有各的理由**,不是把 8 调小了:
 *  · `DRAG_START_PX`(8,**任意方向**)量的是「行 / 瓦上这一下是不是手抖」——
 *    那两种来源的动作是**打开**,误起拖的代价是「想点一下,却冒出一枚浮影」;
 *  · `DRAG_START_X`(6,**只量横向**)量的是「这一格标签是不是要换序」——
 *    换序是标签最常见的拖法,起得要快;而它误起拖的代价近乎为零(浮影不画,
 *    抬起来 6px 又放回去在屏幕上就是没发生过,§4.5 第 2 条保证周围一律不变色)。
 *
 * 6 仍旧比触控板一次点击的横向漂移(2–3px)大,所以「点一下还是点一下」。
 * 竖向那一头不用这个数:标签的竖向阈值是 `TEAR_OFF_DISTANCE`(24,撕下来),
 * 于是同一格标签上两个方向是两件事、两个数 —— 这正是上面那张表的纪律。
 */
export const DRAG_START_X = 6

/**
 * **「放到标签上」那条带的上沿**(W6-b 二修,设计 §4.1 的 `ONTO_FROM` /
 * §4.2 那张状态机)。
 *
 * 指针低于标签条底缘这么多,就从**换序**转进**放到标签上**:邻居不再让位,
 * 指针底下那一格描圈亮起,松手就是二合一。
 *
 * ── 它与 `TEAR_OFF_DISTANCE`(24)夹出的就是那条带 ─────────────────────────
 *   条的底缘 + 6   ← 带的上沿(**这个数**)
 *   条的底缘 + 24  ← 带的下沿 = `TEAR_OFF_DISTANCE`,再往下就是撕下
 *
 * 下沿在这里**不再写第二个 24**:`useTabDrag` 交给 `DragSession` 的 `bandSlack`
 * 本来就是那个数(带的上下外扩),两处读同一个常量,「越过下沿 = 出带 = 撕下」
 * 才是一句真话。多一个 24 意味着某天有人只改了其中一头,于是屏幕上多出一条
 * 既不二合一也不撕下的死区 —— 而那种死区在真机上只表现为「拖到那儿没反应」。
 *
 * ── 为什么是**位置**判据而不是时间 ──────────────────────────────────────
 * 第一版这一下是**按时间判**的:在某个邻居正中停住 300ms 就算「我要并」(一个
 * 时长常量 + 一个手抖上界 + 一个 `--dur-*` token,三样随本批整件退役)。真机上
 * 换序途中稍一停手就误并 —— 而「拖到一半停下来想想」是人的常态,时间判据没有
 * 办法把它和「我要并」分开。位置判据有先例:Finder 里拖**进**文件夹与插到
 * 两项**之间**,分的也是位置(设计 §1 那张出处表最后一行)。
 *
 * 6 与 `DRAG_START_X` 的 6 数值相等而**不是同一件事**(§4.1 那张表的纪律):
 * 那个量「手抖了没有」,这个量「手往下走了没有」;两者的用户反馈来自完全不同的
 * 场合,合并成一个常量以后调其中一头会连带改掉另一头。
 */
export const ONTO_FROM_PX = 6

