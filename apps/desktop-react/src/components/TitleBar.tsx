import s from './TitleBar.module.css'

/**
 * 自绘顶带 —— **我们自己的刘海**(09-01 用户拍板:「我们不要 macOS 自己的刘海,
 * 我们自己设计刘海,让我们的内容直接占满屏幕,注意 window 的拖拽问题」)。
 *
 * ── 它为什么必须存在 ─────────────────────────────────────────────────────
 * 窗口改成 `titleBarStyle: 'hiddenInset'` 之后,系统标题栏没了,整扇窗从 y=0 起
 * 都是网页 —— 顺带没了的还有**唯一能拖动窗口的地方**。所以这条带不是装饰,
 * 它是那个能力的载体:整条 `-webkit-app-region: drag`。
 *
 * ── 拖拽判例(仓里踩过的坑,别再踩)──────────────────────────────────────
 *  ① `-webkit-app-region` 只按**内容盒**算:padding / border 那一圈不是拖拽区。
 *     所以让位不能写成 `padding-left`——那样让出来的地方仍然是可拖的,而真正
 *     需要「别拖」的正是那一块。必须是一个**真元素**占住它。
 *  ② `no-drag` 只有在 drag 元素**同一分支的子孙**上才生效。`.traffic` 是
 *     `.bar` 的直接子元素,这一条成立;将来加控件也必须挂在这条带**里面**,
 *     摆到旁边去的 no-drag 是个不生效的安慰剂。
 *
 * ── 极简版的边界(设计稿轮之前不要往这里加东西)─────────────────────────
 * 今天带上只有两样:一整条拖拽区,和左端那块给红绿灯让位的空白。没有标题、
 * 没有按钮 —— 视觉设计属用户后拍,这一批只把结构和满幅做对。
 * 将来往这里加的**任何**可点件,按 CLAUDE.md「基础件先行」一律消费 `src/ui`
 * 的件(IconButton / Tooltip / …),不许在这条带上手写一颗钮。
 *
 * a11y:整条带没有任何可聚焦、可朗读的内容 —— 它是窗口管理器的一块把手,
 * 不是页面内容。所以 `aria-hidden`,而不是给它编一个假名字。
 */
export function TitleBar() {
  return (
    <div className={s.bar} aria-hidden="true" data-testid="titlebar">
      {/* 红绿灯避让区。原生按钮画在网页之上,这块空白不"画"它们,只是保证
        * 这一段不被当成拖拽把手(否则拖到灯上是拖窗,而不是点灯)。 */}
      <div className={s.traffic} data-testid="titlebar-traffic" />
    </div>
  )
}
