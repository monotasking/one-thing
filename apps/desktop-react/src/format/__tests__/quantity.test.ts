import { describe, expect, it } from 'vitest'
import { formatDuration, formatQuantity } from '../quantity'

/**
 * §5.7 收口之前有**两个产地**在各写各的:`composer/transitions.ts` 的 `formatCount`
 * (小写 k、没有 M、一百万写成 `1000k`)与 `providers/projection.ts` 的 `formatTokens`
 * (大写 K、有 M、不带小数)—— 同一个数在输入框读数里和模型目录里长得不一样。
 * 两个都退役了,这张表是新产地的合同。
 *
 * 表里每一行都是一个**档的边界**,不是随手挑的数:进位的 bug 只长在边界上。
 */
describe('数量:小写 k、大写 M,一位小数,整数不留 .0', () => {
  it.each([
    // 千位以下原样,一个字符都不动。
    [999, '999'],
    // 恰好一千 = 第一个 k;整数不留 .0。
    [1_000, '1k'],
    [1_200, '1.2k'],
    [48_200, '48.2k'],
    [200_000, '200k'],
    /*
     * **先四舍五入再判档**这条纪律的落点:999 950 在 k 档上会四舍五入成 1000.0k,
     * 而 `1000k` 不是任何人想读的写法 —— 它必须进到 M 档。旧的 formatCount 正是
     * 在这里说了 `1000k`。
     */
    [999_950, '1M'],
    [1_000_000, '1M'],
    [1_250_000, '1.3M'],
    [128_000_000, '128M'],
    // 负数:符号在外面,档与小数位与正数逐字同一套。
    [-1_200, '-1.2k'],
    [-999, '-999'],
  ])('%i → %s', (n, want) => {
    expect(formatQuantity(n)).toBe(want)
  })
})

describe('时间:只到 0.1s,永不写毫秒', () => {
  it.each([
    [0, '0.0s'],
    // 从前 `content/tools/status.ts` 在一秒以下写 `339ms` —— 同一张卡上两种单位换来换去。
    [339, '0.3s'],
    [4_160, '4.2s'],
    /*
     * 59 950ms 仍在秒档(判据是 `< 60_000`,不是「四舍五入后还不到一分钟」)——
     * 它读作 60.0s。把判据挪到取整之后会让 59.95s 与 60.00s 长得一样,
     * 而那两个数在读数里本来就该看得出先后。
     */
    [59_950, '60.0s'],
    // 分钟档不带小数(拍点 ⑮),秒补零到两位。
    [60_000, '1m 00s'],
    [65_300, '1m 05s'],
    // 非数 / 负数按 0 算:读数不显示负时间,也不显示 NaN。
    [Number.NaN, '0.0s'],
    [-1, '0.0s'],
  ])('%i ms → %s', (ms, want) => {
    expect(formatDuration(ms)).toBe(want)
  })
})
